import { database, ensureAuthTables, requireUser } from '../../api/_lib/auth.js';
import { resolveSchoolId } from '../../api/_lib/canonicalSubmissions.js';
import { checkRateLimit } from '../../api/_lib/rateLimit.js';
import { checkAiRateLimit, getStudentTier } from '../../api/_lib/aiRateLimitTiers.js';
import { InsufficientEvidenceError } from '../../api/_lib/contextBuilder.js';
import { handleCors } from '../../api/_lib/cors.js';
import { internalError } from '../../api/_lib/httpError.js';
import {
  generatePracticeTest,
  getPracticeTest,
  gradePracticeSubmission,
  listPracticeTests,
} from '../../api/_lib/practice.js';

function parseBody(req) {
  if (!req.body) return {};
  if (typeof req.body === 'object') return req.body;
  try {
    return JSON.parse(req.body);
  } catch {
    return {};
  }
}

async function schoolIdForUser(db, user) {
  if (user.school_id) return user.school_id;
  if (!user.school) return null;
  return resolveSchoolId(db, user.school);
}

function assertStudentAccess(user, requestedUsername) {
  const staff = ['teacher', 'admin', 'skyll_admin'].includes(user.role);
  if (requestedUsername && requestedUsername !== user.username && !staff) {
    return false;
  }
  return true;
}

// A student may open or grade only a test they own. A test with no owning
// username (generated by staff for a studentId) is not theirs (FLKRM-383).
function canAccessPracticeTest(user, practiceTest) {
  if (['teacher', 'admin', 'skyll_admin'].includes(user.role)) return true;
  return Boolean(practiceTest.username) && practiceTest.username === user.username;
}

function withoutAnswerKey(question) {
  if (!question || typeof question !== 'object') return question;
  const next = { ...question };
  delete next.answerKey;
  delete next.rubric;
  return next;
}

/** /api/ai/practice — generate, fetch, or grade practice tests. */
export default async function handler(req, res) {
  if (handleCors(req, res)) return;

  try {
    await ensureAuthTables();
    const user = await requireUser(req, res, ['student', 'teacher', 'admin', 'skyll_admin']);
    if (!user) return;

    if (await checkRateLimit(`practice:${user.user_id || user.username}`, { max: 15, windowMs: 60_000 })) {
      return res.status(429).json({ error: 'Too many practice requests. Try again shortly.' });
    }

    const db = database();
    const schoolId = await schoolIdForUser(db, user);
    const body = ['POST', 'PUT', 'PATCH'].includes(req.method) ? parseBody(req) : {};
    const scopedSchoolId = String(body.schoolId || req.query?.schoolId || schoolId || '').trim();
    if (!scopedSchoolId) return res.status(400).json({ error: 'schoolId is required' });
    if (user.role !== 'skyll_admin' && scopedSchoolId !== schoolId) {
      return res.status(403).json({ error: 'School access denied' });
    }

    if (req.method === 'GET') {
      if (req.query?.list) {
        const requestedUsername = String(req.query?.username || '').trim();
        if (!assertStudentAccess(user, requestedUsername)) {
          return res.status(403).json({ error: 'You do not have permission for this student' });
        }
        // Students always see only their own tests; staff may scope by username or view the school's.
        const username = user.role === 'student' ? user.username : requestedUsername || null;
        const practiceTests = await listPracticeTests(db, {
          schoolId: scopedSchoolId,
          username,
          limit: req.query?.limit,
        });
        res.setHeader('Cache-Control', 'private, no-store');
        return res.status(200).json({ practiceTests });
      }
      const practiceTestId = String(req.query?.id || req.query?.practiceTestId || '').trim();
      if (!practiceTestId) return res.status(400).json({ error: 'id is required' });
      const practiceTest = await getPracticeTest(db, { practiceTestId, schoolId: scopedSchoolId });
      if (!practiceTest) return res.status(404).json({ error: 'Practice test not found' });
      if (!canAccessPracticeTest(user, practiceTest)) {
        return res.status(403).json({ error: 'You do not have permission for this practice test' });
      }
      // Strip answer keys for students still taking the test.
      const hideKeys = practiceTest.status !== 'graded' && user.role === 'student';
      const questions = hideKeys
        ? practiceTest.questions.map(withoutAnswerKey)
        : practiceTest.questions;
      res.setHeader('Cache-Control', 'private, no-store');
      return res.status(200).json({ practiceTest: { ...practiceTest, questions } });
    }

    if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

    const action = String(body.action || 'generate').trim().toLowerCase();
    const requestedUsername = String(body.username || body.student || '').trim();
    if (!assertStudentAccess(user, requestedUsername)) {
      return res.status(403).json({ error: 'You do not have permission for this student' });
    }

    if (action === 'grade') {
      const practiceTestId = String(body.practiceTestId || body.id || '').trim();
      if (!practiceTestId) return res.status(400).json({ error: 'practiceTestId is required' });
      const existing = await getPracticeTest(db, { practiceTestId, schoolId: scopedSchoolId });
      if (!existing) return res.status(404).json({ error: 'Practice test not found' });
      if (!canAccessPracticeTest(user, existing)) {
        return res.status(403).json({ error: 'You do not have permission for this practice test' });
      }
      const student = user.role === 'student';
      const result = await gradePracticeSubmission(db, {
        schoolId: scopedSchoolId,
        practiceTestId,
        answers: body.answers || [],
        username: student ? existing.username : requestedUsername || existing.username || null,
        studentId: student ? existing.studentId || null : body.studentId || existing.studentId || null,
      });
      res.setHeader('Cache-Control', 'private, no-store');
      return res.status(200).json(result);
    }

    // default: generate
    // Fair-use weekly quota (tier-aware) for student self-generation; grading an
    // existing test and staff generation are exempt.
    if (user.role === 'student') {
      const tier = await getStudentTier(db, { userId: user.user_id, schoolId: scopedSchoolId });
      const quota = await checkAiRateLimit(user.user_id || user.username, 'practice', tier);
      if (quota.limited) {
        return res.status(429).json({
          error: `Weekly practice-test limit reached (${quota.limit}/week on your plan). Try again next week.`,
          limit: quota.limit, used: quota.used, tier,
        });
      }
    }

    const count = Math.max(3, Math.min(8, Number(body.count) || 5));
    const topics = Array.isArray(body.topics)
      ? body.topics
      : String(body.topic || '')
        .split('|')
        .map((topic) => topic.trim())
        .filter(Boolean);

    // Students generate only for themselves; a client studentId is ignored (FLKRM-383).
    const student = user.role === 'student';
    const practiceTest = await generatePracticeTest(db, {
      schoolId: scopedSchoolId,
      username: student ? user.username : requestedUsername || null,
      studentId: student ? null : body.studentId || null,
      subject: String(body.subject || 'Mathematics').trim() || 'Mathematics',
      topics: topics.length ? topics : null,
      count,
      generatedBy: user.role === 'student' ? 'self_request' : 'teacher',
    });

    const questions = practiceTest.questions.map(withoutAnswerKey);
    res.setHeader('Cache-Control', 'private, no-store');
    return res.status(201).json({
      practiceTest: { ...practiceTest, questions },
    });
  } catch (error) {
    if (error instanceof InsufficientEvidenceError) {
      res.setHeader('Cache-Control', 'private, no-store');
      return res.status(200).json({ ok: false, reason: 'insufficient_data', evidence: error.evidence });
    }
    return internalError(res, error, 'ai/practice');
  }
}
